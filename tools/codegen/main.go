type tplData struct {
	Package   string
	TypeName  string
	Name      string
	Index     int
	Kind      string
	BodyLines []string
}

func main() {
	root, err := findModuleRoot()
	if err != nil {
		fmt.Fprintf(os.Stderr, "module root: %v\n", err)
		os.Exit(1)
	}

	modTpl := template.Must(template.New("mod").Parse(moduleTpl))
	testT := template.Must(template.New("test").Parse(testTpl))
	benchT := template.Must(template.New("bench").Parse(benchTpl))

	total := 0
	for _, s := range specs {
		n, err := emitSpec(root, s, modTpl, testT, benchT)
		if err != nil {
			fmt.Fprintf(os.Stderr, "emit %s: %v\n", s.Dir, err)
			os.Exit(1)
		}
		total += n
		fmt.Printf("generated %d files in %s\n", n, s.Dir)
	}

	if err := emitRegistry(root); err != nil {
		fmt.Fprintf(os.Stderr, "registry: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("codegen complete: %d files\n", total+1)
}

func emitSpec(root string, s spec, modTpl, testT, benchT *template.Template) (int, error) {
	if err := os.MkdirAll(filepath.Join(root, s.Dir), 0o755); err != nil {
		return 0, err
	}

	count := 0
	for i := 1; i <= s.Count; i++ {
		typeName := fmt.Sprintf("%s%s%03d", title(s.Kind), title(s.Prefix), i)
		name := fmt.Sprintf("%s_%03d", s.Prefix, i)
		body := make([]string, 0, s.Lines-40)
		for j := 0; j < s.Lines-40; j++ {
			body = append(body, fmt.Sprintf(`"line-%d-%d"`, i, j))
		}
		data := tplData{
			Package:   s.Package,
			TypeName:  typeName,
			Name:      name,
			Index:     i,
			Kind:      s.Kind,
			BodyLines: body,
		}

		outPath := filepath.Join(root, s.Dir, fmt.Sprintf("%s_%03d.go", s.Prefix, i))
		if err := writeTemplate(outPath, modTpl, data); err != nil {
			return count, err
		}
		count++

		if s.TestFile {
			testPath := filepath.Join(root, s.Dir, fmt.Sprintf("%s_%03d_test.go", s.Prefix, i))
			if err := writeTemplate(testPath, testT, data); err != nil {
				return count, err
			}
			count++
			if s.Kind == "benchmark" {
				benchPath := filepath.Join(root, s.Dir, fmt.Sprintf("%s_%03d_bench_test.go", s.Prefix, i))
				if err := writeTemplate(benchPath, benchT, data); err != nil {
					return count, err
				}
				count++
			}
		}
	}
	return count, nil
}

func writeTemplate(path string, tpl *template.Template, data tplData) error {
	var b strings.Builder
	if err := tpl.Execute(&b, data); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func emitRegistry(root string) error {
	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen; DO NOT EDIT.\n")
	b.WriteString("package registry\n\n")
	b.WriteString("import \"fmt\"\n\n")
	b.WriteString("// ModuleCount reports generated module totals.\n")
	b.WriteString("func ModuleCount() int {\n\treturn ")
	totalMods := 0
	for _, s := range specs {
		if !s.TestFile {
			totalMods += s.Count
		}
	}
	b.WriteString(fmt.Sprintf("%d\n}\n\n", totalMods))
	b.WriteString("// Subsystems lists codegen subsystem directories.\n")
	b.WriteString("func Subsystems() []string {\n\treturn []string{\n")
	for _, s := range specs {
		if s.TestFile {
			continue
		}
		b.WriteString(fmt.Sprintf("\t\t%q,\n", s.Dir))
	}
	b.WriteString("\t}\n}\n")
	path := filepath.Join(root, "internal/registry/registry.go")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func title(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func findModuleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found")
		}
		dir = parent
	}
}
