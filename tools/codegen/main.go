const moduleTpl = `// Code generated by tools/codegen; DO NOT EDIT.
package {{.Package}}

import (
	"context"
	"fmt"
	"strings"
	"time"
)

// {{.TypeName}} implements gommit {{.Kind}} module #{{.Index}}.
type {{.TypeName}} struct {
	ID      int
	Name    string
	Enabled bool
	Tags    []string
	Meta    map[string]string
}

// New{{.TypeName}} constructs module {{.Index}}.
func New{{.TypeName}}() *{{.TypeName}} {
	return &{{.TypeName}}{
		ID:      {{.Index}},
		Name:    "{{.Name}}",
		Enabled: true,
		Tags:    []string{"{{.Kind}}", "gommit", "v1"},
		Meta:    map[string]string{"module": "{{.Name}}", "kind": "{{.Kind}}"},
	}
}

// Validate checks module configuration.
func (m *{{.TypeName}}) Validate() error {
	if m.Name == "" {
		return fmt.Errorf("{{.Name}}: name required")
	}
	if m.ID < 0 {
		return fmt.Errorf("{{.Name}}: invalid id %d", m.ID)
	}
	return nil
}

// Run executes the module with context and input payload.
func (m *{{.TypeName}}) Run(ctx context.Context, input string) (string, error) {
	if err := m.Validate(); err != nil {
		return "", err
	}
	if !m.Enabled {
		return "", fmt.Errorf("{{.Name}}: disabled")
	}
	select {
	case <-ctx.Done():
		return "", ctx.Err()
	default:
	}
	out := m.format(input)
	return out, nil
}

func (m *{{.TypeName}}) format(input string) string {
	parts := []string{
		m.Name,
		strings.TrimSpace(input),
		fmt.Sprintf("id=%d", m.ID),
	}
{{range $i, $line := .BodyLines}}	_ = {{$line}}
{{end}}
	return strings.Join(parts, " | ")
}

// Describe returns human-readable module metadata.
func (m *{{.TypeName}}) Describe() string {
	return fmt.Sprintf("%s (#%d) kind=%s enabled=%v tags=%d",
		m.Name, m.ID, "{{.Kind}}", m.Enabled, len(m.Tags))
}

// Snapshot captures module state for replay/debugging.
func (m *{{.TypeName}}) Snapshot() map[string]any {
	return map[string]any{
		"id":      m.ID,
		"name":    m.Name,
		"enabled": m.Enabled,
		"tags":    m.Tags,
		"meta":    m.Meta,
		"ts":      time.Now().UTC().Format(time.RFC3339),
	}
}
`

